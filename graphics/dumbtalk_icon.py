"""Generates the launcher icon's foreground: a dot-matrix speech bubble.

    python3 graphics/dumbtalk_icon.py > app/src/main/res/drawable/ic_launcher_foreground.xml

The same file is used as the monochrome layer. Dots stay inside the
adaptive icon's 66dp safe zone so any launcher mask shape works.
"""
GRID = """
..XXXXXXXXXX..
.XXXXXXXXXXXX.
XXXXXXXXXXXXXX
XXXXXXXXXXXXXX
XXXXXXXXXXXXXX
XXXXXXXXXXXXXX
.XXXXXXXXXXXX.
..XXXXXXXXXX..
..XXX.........
..XX..........
..X...........
""".strip().split("\n")

CELL, RADIUS = 3.4, 1.4
ox = (108 - len(GRID[0]) * CELL) / 2
oy = (108 - len(GRID) * CELL) / 2
dots = [(ox + c * CELL + CELL / 2, oy + y * CELL + CELL / 2)
        for y, row in enumerate(GRID) for c, ch in enumerate(row) if ch == "X"]
r = RADIUS
path = "".join(f"M{x - r:.2f},{y:.2f}a{r},{r} 0 1,0 {2 * r},0a{r},{r} 0 1,0 {-2 * r},0z" for x, y in dots)
print(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- DumbTalk: a dot-matrix speech bubble. Generated by graphics/dumbtalk_icon.py; inside the 66dp safe zone. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="#FFFFFFFF"
        android:pathData="{path}" />
</vector>''')
